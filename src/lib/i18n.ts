const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, th };

export type TranslateValues = Record<string, string | number>;

export const translate = (language: Language, key: TranslationKey, values?: TranslateValues) => {
    const template = dictionaries[language][key];
    if (!values) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
        name in values ? String(values[name]) : match
    );
};

/**
 * `-u-ca-gregory` keeps Thai month and weekday names but leaves the year in the
 * Gregorian era, matching what is stored in the database and shown everywhere else.
 */
export const dateLocaleTag: Record<Language, string> = { en: 'en-US', th: 'th-TH-u-ca-gregory' };

export const formatDate = (language: Language, date: Date, options: Intl.DateTimeFormatOptions) =>
    new Intl.DateTimeFormat(dateLocaleTag[language], options).format(date);

/** Short weekday labels starting on Sunday, to match the calendar grid. */
export const weekdayNames = (language: Language) => {
    const sunday = new Date(2024, 0, 7);
    return Array.from({ length: 7 }, (_, index) => {
        const day = new Date(sunday);
        day.setDate(sunday.getDate() + index);
        return formatDate(language, day, { weekday: 'short' });
    });
};
